import type { ParsedSchema } from '../parsers/schema-parser.js';

export interface ValidatorOptions {
  /**
   * Also emit a fit function per schema (OCPP 2.0.1). The CSMS builds its payloads in the 2.1
   * shape; a fit function returns a deep copy without the properties the older schema does not
   * allow, so the payload can go to a 2.0.1 station. It removes properties only: enum values and
   * lengths need explicit mappings.
   */
  fit?: boolean;
}

export function generateValidatorFile(
  schema: ParsedSchema,
  options: ValidatorOptions = {},
): string {
  const messageName = schema.fileName.replace('.json', '');
  // Strip meta-schema fields that cause AJV 8 compatibility issues
  // AJV 8 does not support Draft-04 "id" field (use "$id" instead) and
  // complains about "$schema" when the referenced meta-schema is not loaded
  const cleanedSchema = { ...schema.rawSchema } as Record<string, unknown>;
  delete cleanedSchema['$schema'];
  delete cleanedSchema['id'];
  const schemaJson = JSON.stringify(cleanedSchema, null, 2);

  const lines: string[] = [];

  lines.push(`import type { ValidateFunction } from 'ajv';`);
  lines.push(`import { ajv } from './_ajv.js';`);
  if (options.fit === true) {
    lines.push(`import { ajvFit } from './_ajv-fit.js';`);
  }
  lines.push('');
  lines.push(`const schema = ${schemaJson} as const;`);
  lines.push('');
  lines.push(`export const validate${messageName}: ValidateFunction = ajv.compile(schema);`);

  if (options.fit === true) {
    lines.push('');
    lines.push(`const removeAdditional${messageName}: ValidateFunction = ajvFit.compile(schema);`);
    lines.push('');
    lines.push(`/**`);
    lines.push(
      ` * Returns a deep copy of the payload without the properties this schema does not allow.`,
    );
    lines.push(
      ` * The input is not changed. The copy is not validated: call validate${messageName} for that.`,
    );
    lines.push(` */`);
    lines.push(
      `export function fit${messageName}(payload: Record<string, unknown>): Record<string, unknown> {`,
    );
    lines.push(`  const copy = structuredClone(payload);`);
    lines.push(`  removeAdditional${messageName}(copy);`);
    lines.push(`  return copy;`);
    lines.push(`}`);
  }

  return lines.join('\n') + '\n';
}

export function generateAjvSetupFile(): string {
  const lines: string[] = [];

  lines.push(`// @ts-nocheck`);
  lines.push(`// Auto-generated by @evtivity/codegen - CJS/ESM interop requires ts-nocheck`);
  lines.push(`import Ajv from 'ajv';`);
  lines.push(`import addFormats from 'ajv-formats';`);
  lines.push('');
  lines.push(`const ajv = new Ajv({`);
  lines.push(`  allErrors: true,`);
  lines.push(`  strict: false,`);
  lines.push(`  validateSchema: false,`);
  lines.push(`});`);
  lines.push('');
  lines.push(`addFormats(ajv);`);
  lines.push('');
  lines.push(`export { ajv };`);

  return lines.join('\n') + '\n';
}

/**
 * A second Ajv instance for the fit functions. `removeAdditional: true` deletes every property an
 * `additionalProperties: false` object does not list. Every OCPP 2.0.1 object type has
 * `additionalProperties: false` except CustomDataType, which the schema leaves open for vendor
 * fields, so those stay (`'all'` would strip them although the schema allows them). `allErrors`
 * keeps the walk going past the first error, so a payload that also fails another keyword still
 * loses all its extra properties. Kept apart from the validating instance, which must never
 * change a payload.
 */
export function generateAjvFitSetupFile(): string {
  const lines: string[] = [];

  lines.push(`// @ts-nocheck`);
  lines.push(`// Auto-generated by @evtivity/codegen - CJS/ESM interop requires ts-nocheck`);
  lines.push(`import Ajv from 'ajv';`);
  lines.push(`import addFormats from 'ajv-formats';`);
  lines.push('');
  lines.push(`const ajvFit = new Ajv({`);
  lines.push(`  allErrors: true,`);
  lines.push(`  strict: false,`);
  lines.push(`  validateSchema: false,`);
  lines.push(`  removeAdditional: true,`);
  lines.push(`});`);
  lines.push('');
  lines.push(`addFormats(ajvFit);`);
  lines.push('');
  lines.push(`export { ajvFit };`);

  return lines.join('\n') + '\n';
}
