/** The policy of an operation; an operation without an entry is never a tool. */
export function toolPolicy(operationId: string): ToolPolicy {
  return Object.prototype.hasOwnProperty.call(AI_TOOL_POLICY, operationId)
    ? (AI_TOOL_POLICY[operationId] ?? N)
    : N;
}

/** Whether `surface` offers the operation. */
export function surfaceOffers(policy: ToolPolicy, surface: AiSurface): boolean {
  if (policy.exposure === 'never') return false;
  return surface === 'chatbot' ? policy.chatbot : policy.support !== null;
}

