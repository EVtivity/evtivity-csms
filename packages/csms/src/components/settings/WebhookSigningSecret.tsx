import { useState } from 'react';
import { useTranslation } from 'react-i18next';
import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query';
import { Button } from '@/components/ui/button';
import { ConfirmDialog } from '@/components/ui/confirm-dialog';
import { CopyButton } from '@/components/ui/copy-button';
import { Label } from '@/components/ui/label';
import { api } from '@/lib/api';
import { getErrorMessage } from '@/lib/error-message';

const PATH = '/v1/settings/notifications/webhook-signing-secret';
const QUERY_KEY = ['settings', 'webhook-signing-secret'];

/**
 * The webhook signing secret: generated by the API and shown here once.
 * Receivers verify `X-EVtivity-Signature` with it.
 */
export function WebhookSigningSecret(): React.JSX.Element {
  const { t } = useTranslation();
  const queryClient = useQueryClient();
  const [shown, setShown] = useState<string | null>(null);
  const [confirm, setConfirm] = useState<'regenerate' | 'remove' | null>(null);

  const status = useQuery({
    queryKey: QUERY_KEY,
    queryFn: () => api.get<{ configured: boolean }>(PATH),
    staleTime: 60_000,
  });
  const configured = status.data?.configured === true;

  const generate = useMutation({
    mutationFn: () => api.post<{ secret: string }>(PATH, {}),
    onSuccess: (data) => {
      setShown(data.secret);
      setConfirm(null);
      void queryClient.invalidateQueries({ queryKey: QUERY_KEY });
    },
  });
  const remove = useMutation({
    mutationFn: () => api.delete<{ configured: boolean }>(PATH),
    onSuccess: () => {
      setShown(null);
      setConfirm(null);
      void queryClient.invalidateQueries({ queryKey: QUERY_KEY });
    },
  });

  return (
    <div className="space-y-2">
      <Label className="leading-6">{t('settings.webhookSigningSecret')}</Label>
      <p className="text-xs text-muted-foreground">{t('settings.webhookSigningSecretHint')}</p>
      <p className="text-sm">
        {configured
          ? t('settings.webhookSigningSecretConfigured')
          : t('settings.webhookSigningSecretNotConfigured')}
      </p>
      {shown != null && (
        <div className="space-y-1 rounded-md border p-3">
          <p className="text-xs text-muted-foreground">
            {t('settings.webhookSigningSecretShownOnce')}
          </p>
          <div className="flex items-center gap-2">
            <code className="break-all text-sm" data-testid="webhook-signing-secret">
              {shown}
            </code>
            <CopyButton value={shown} size="icon" />
          </div>
        </div>
      )}
      <div className="flex justify-end gap-2">
        {configured && (
          <Button
            type="button"
            variant="outline"
            onClick={() => {
              setConfirm('remove');
            }}
          >
            {t('settings.webhookSigningSecretRemove')}
          </Button>
        )}
        <Button
          type="button"
          disabled={generate.isPending}
          onClick={() => {
            if (configured) setConfirm('regenerate');
            else generate.mutate();
          }}
        >
          {configured
            ? t('settings.webhookSigningSecretRegenerate')
            : t('settings.webhookSigningSecretGenerate')}
        </Button>
      </div>
      {(generate.isError || remove.isError) && (
        <p className="text-sm text-destructive">
          {t('settings.webhookSigningSecretFailed')}{' '}
          {getErrorMessage(generate.error ?? remove.error, t)}
        </p>
      )}
      <ConfirmDialog
        open={confirm === 'regenerate'}
        onOpenChange={(open) => {
          if (!open) setConfirm(null);
        }}
        title={t('settings.webhookSigningSecretRegenerate')}
        description={t('settings.webhookSigningSecretRegenerateConfirm')}
        confirmLabel={t('settings.webhookSigningSecretRegenerate')}
        isPending={generate.isPending}
        onConfirm={() => {
          generate.mutate();
        }}
      />
      <ConfirmDialog
        open={confirm === 'remove'}
        onOpenChange={(open) => {
          if (!open) setConfirm(null);
        }}
        title={t('settings.webhookSigningSecretRemove')}
        description={t('settings.webhookSigningSecretRemoveConfirm')}
        confirmLabel={t('settings.webhookSigningSecretRemove')}
        isPending={remove.isPending}
        onConfirm={() => {
          remove.mutate();
        }}
      />
    </div>
  );
}
